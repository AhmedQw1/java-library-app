    private void ADDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ADDActionPerformed
        String isbnStr = ISBN.getText().trim();
        String titleStr = TITLE.getText().trim();
        String authorStr = AUTHOR.getText().trim();
        String genreStr = GENRE.getText().trim();
        String yearStr = YEAR.getText().trim();

        if (!isbnStr.matches("\\d+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "ISBN must be a number!", "Invalid ISBN", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }

        if (titleStr.isEmpty() || authorStr.isEmpty() || genreStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Title, Author, and Genre cannot be empty!", "Missing Info", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int year;
        try {
            year = Integer.parseInt(yearStr);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Year must be a valid number!", "Invalid Year", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (SIZE.isVisible()) {
            String formatStr = FORMAT.getText().trim();
            String sizeStr = SIZE.getText().trim();

            if (formatStr.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Format cannot be empty for an eBook!", "Missing Info", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            double size;
            try {
                size = Double.parseDouble(sizeStr);
            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Size (MB) must be a valid number!", "Invalid Size", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            resultBook = new EBook(isbnStr, titleStr, authorStr, genreStr, year, formatStr, size);
            
        } else {
            resultBook = new Book(isbnStr, titleStr, authorStr, genreStr, year);
        }
        this.dispose();
    }//GEN-LAST:event_ADDActionPerformed

