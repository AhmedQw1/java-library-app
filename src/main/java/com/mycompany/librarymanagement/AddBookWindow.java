    public void setupForEdit(Book b) {
        this.setTitle("Edit Book");
        
        ISBN.setText(b.getIsbn());
        ISBN.setEditable(true); 
        TITLE.setText(b.getTitle());
        AUTHOR.setText(b.getAuthor());
        GENRE.setText(b.getGenre());
        YEAR.setText(String.valueOf(b.getYear()));
        
        if (b instanceof EBook) {
            EBook eb = (EBook) b; 
            
            FORMAT.setText(eb.getFileFormat());
            SIZE.setText(String.valueOf(eb.getFileSizeMB())); 
            
            FORMAT.setVisible(true);
            SIZE.setVisible(true);
            jLabel6.setVisible(true);
            jLabel7.setVisible(true);
        } else {
            FORMAT.setVisible(false);
            SIZE.setVisible(false);
            jLabel6.setVisible(false);
            jLabel7.setVisible(false);
        }
    }



